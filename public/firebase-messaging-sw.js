/*
 * firebase-messaging-sw.js — Firebase Service Worker (Background Push)
 *
 * Handles push notifications when the ConnectHub tab is closed or not focused.
 * Firebase suppresses browser notifications when the page is in the foreground;
 * the main app handles those via initForegroundListener() in firebase.js.
 *
 * CONFIG STRATEGY:
 *   Service workers live in /public and are NOT processed by Vite, so VITE_ env
 *   vars cannot be injected here via import.meta.env. Two-layer config loading:
 *
 *   1. PRIMARY — importScripts('/firebase-sw-config.js') loads a file generated
 *      by the Vite generateFirebaseSwConfig() plugin at build/dev time. This file
 *      sets self.FIREBASE_SW_CONFIG synchronously so Firebase can be initialised
 *      at script evaluation time, satisfying the browser requirement that push/
 *      pushsubscriptionchange/notificationclick handlers be registered then.
 *
 *   2. FALLBACK — if the config file is missing (pre-build local dev), the sw
 *      waits for a FIREBASE_CONFIG postMessage from the main thread (old approach).
 *      The postMessage path still works but triggers a browser warning about late
 *      handler registration; the primary path avoids that warning entirely.
 *
 * NOTIFICATION CLICK:
 *   Clicking a notification focuses the ConnectHub tab (or opens it) so the user
 *   lands directly in the chat.
 */

/* global firebase */
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-app-compat.js')
importScripts('https://www.gstatic.com/firebasejs/10.12.0/firebase-messaging-compat.js')

// ── Primary: load config that was generated by the Vite plugin at build time ──
// The try/catch makes this graceful — if the file doesn't exist (pre-build dev)
// the SW falls back to the postMessage handshake below.
try {
  importScripts('/firebase-sw-config.js')
} catch (_) {
  // firebase-sw-config.js not available — will wait for postMessage config below
}

// ── Initialise Firebase eagerly if config is available now ────────────────────
let messagingReady = false

function initFirebase(config) {
  if (messagingReady) return
  if (!config?.apiKey || !config?.projectId) return // incomplete config

  try {
    if (!firebase.apps.length) {
      firebase.initializeApp(config)
    }
    const messaging = firebase.messaging()
    messagingReady = true

    // ── Background message handler ─────────────────────────────────────────────
    // This must be registered at initial evaluation time (or as early as possible)
    // so the browser can reliably deliver push events.
    messaging.onBackgroundMessage((payload) => {
      const title   = payload.notification?.title || 'ConnectHub'
      const body    = payload.notification?.body  || 'You have a new notification'
      const roomId  = payload.data?.roomId        || ''
      const type    = payload.data?.type          || ''

      const iconMap = {
        NEW_MESSAGE: '/icon-message.png',
        MENTION:     '/icon-mention.png',
        ROOM_INVITE: '/icon-invite.png',
      }

      self.registration.showNotification(title, {
        body,
        icon:     iconMap[type] || '/vite.svg',
        badge:    '/vite.svg',
        data:     { roomId, url: self.location.origin + '/chat' },
        tag:      'connecthub-' + (roomId || 'general'), // collapses notifications per room
        renotify: true,
        vibrate:  [200, 100, 200],
      })
    })
  } catch (e) {
    console.error('[SW] Firebase init failed:', e)
  }
}

// Try to init immediately using config from importScripts above
// (self.FIREBASE_SW_CONFIG is set by public/firebase-sw-config.js)
if (typeof self.FIREBASE_SW_CONFIG !== 'undefined') {
  initFirebase(self.FIREBASE_SW_CONFIG)
}

// ── Fallback: receive Firebase config from the main thread via postMessage ────
// Triggered when the Vite-generated config file was not available (pre-build dev).
self.addEventListener('message', (event) => {
  if (event.data?.type !== 'FIREBASE_CONFIG') return
  initFirebase(event.data.config)
})

// ── Notification click — focus / open the chat tab ────────────────────────────
self.addEventListener('notificationclick', (event) => {
  event.notification.close()

  const targetUrl = event.notification.data?.url || self.location.origin + '/chat'

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      // If ConnectHub is already open, focus it
      for (const client of clientList) {
        if (client.url.startsWith(self.location.origin) && 'focus' in client) {
          return client.focus()
        }
      }
      // Otherwise open a new tab
      if (clients.openWindow) return clients.openWindow(targetUrl)
    }),
  )
})
